"""R08: macros and supplement table for the nested grading check (reads r08_nested_grading.py outputs)."""
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "outputs"
GEN = HERE.parents[2] / "paper" / "manuscript" / "generated"
TOST = HERE.parents[1] / "R07_merged_protocol_2026-10-22" / "outputs" / "tost_verdicts.csv"

TERMS = [("DEEP", "BEAM", "ln_ad", "Beam", "Deep beams BEAM", "$a/d$ (silence)"),
         ("FRP", "K1", "ln_ad", "FrpKi", "FRP K1", "$a/d$ (silence)"),
         ("FRP", "K2", "ln_ad", "FrpKii", "FRP K2", "$a/d$ (silence)"),
         ("SFRC", "K1", "ln1p_F", "SfrcKi", "SFRC K1", "fibre factor $F$"),
         ("SFRC", "K2", "ln1p_F", "SfrcKii", "SFRC K2", "fibre factor $F$")]


def fp(p):
    return r"$<10^{-4}$" if p < 1e-4 else f"{p:.3f}"


def pct(x):
    return f"{100 * x:.0f}"


def main():
    W = pd.read_csv(OUT / "nested_wholedb.csv")
    L = pd.read_csv(OUT / "nested_lopo.csv")
    S = pd.read_csv(OUT / "nested_sub.csv")
    T = pd.read_csv(TOST)
    mac, rows = {}, []
    for dom, rung, feat, tag, lab, term in TERMS:
        w = W[(W.domain == dom) & (W.rung == rung) & (W.feature == feat)].iloc[0]
        lo = L[(L.domain == dom) & (L.rung == rung) & (L.feature == feat)].iloc[0]
        s = S[(S.domain == dom) & (S.rung == rung) & (S.feature == feat)].set_index("S")
        mac[f"nsP{tag}"], mac[f"nsPH{tag}"] = fp(w.p), fp(w.p_holm)
        mac[f"nsLopo{tag}"], mac[f"nsLopoH{tag}"] = pct(lo.share_contra), pct(lo.share_contra_holm)
        mac[f"nsSubSix{tag}"], mac[f"nsSubTfour{tag}"] = pct(s.loc[6, "share_contra"]), pct(s.loc[24, "share_contra"])
        rows.append(f"{lab} & {term} & {fp(w.p)} & {fp(w.p_holm)} & {pct(lo.share_contra)} & "
                    f"{pct(lo.share_contra_holm)} & {pct(s.loc[6, 'share_contra'])} & "
                    f"{pct(s.loc[12, 'share_contra'])} & {pct(s.loc[24, 'share_contra'])} \\\\")
    other = S[S.verdict_wholedb != "CONTRADICTED"]
    six = other[other.S == 6]
    mac["nsFalseMax"] = f"{100 * six.share_contra.max():.1f}"
    mac["nsFalseMean"] = f"{100 * six.share_contra.mean():.1f}"
    lo_other = L[L.verdict_wholedb != "CONTRADICTED"]
    mac["nsFalseLopoMax"] = pct(lo_other.share_contra.max())
    rows.append(r"\midrule")
    rows.append(f"All other 45 terms & (maximum) & -- & -- & {pct(lo_other.share_contra.max())} & "
                f"{pct(lo_other.share_contra_holm.max())} & {100 * six.share_contra.max():.1f} & "
                f"{100 * other[other.S == 12].share_contra.max():.1f} & "
                f"{100 * other[other.S == 24].share_contra.max():.1f} \\\\")
    sf = T[(T.domain == "SFRC") & (T.rung == "K1") & (T.feature == "ln1p_F")].iloc[0]
    mac["nsSfrcSlope"] = f"\\ensuremath{{-}}{abs(sf.data_exp):.2f}" if sf.data_exp < 0 else f"{sf.data_exp:.2f}"
    mac["nsSfrcSlopeSe"] = f"{sf.dW_se:.2f}"
    mac["nsSfrcCoded"] = f"\\ensuremath{{+}}{sf.anchor_implied:.2f}"
    lines = ["% generated by r08_nested_tables.py -- do not edit"]
    lines += [f"\\providecommand{{\\{k}}}{{{v}}}" for k, v in mac.items()]
    lines += ["% --- macro index ---"] + [f"% \\{k} = {v}" for k, v in mac.items()]
    (GEN / "numbers_r08b.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (GEN / "tab_nested.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    for k, v in mac.items():
        print(k, "=", v)
    print("\n".join(rows))


if __name__ == "__main__":
    main()
