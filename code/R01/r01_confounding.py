"""R01 diagnostic 1: how much of each physical effect is identified only *between*
test programmes, and do within- and between-programme effect estimates disagree?

Outputs (round-local, regenerated by this script):
  outputs/confounding_features.csv   per dataset x feature: between share, programmes
                                     that vary the feature, within/between slopes
  outputs/confounding_summary.json   anchor residual structure per dataset
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

import kag_data as K
from kag_models import KnowledgeAnchoredLMM, lmm_gls, within_between

warnings.filterwarnings("ignore")
OUT = Path(__file__).resolve().parents[1] / "outputs"
OUT.mkdir(exist_ok=True)


def between_share(x, g):
    df = pd.DataFrame({"x": x, "g": g})
    gm = df.groupby("g").x.transform("mean")
    tot = np.sum((df.x - df.x.mean()) ** 2)
    return float(np.sum((gm - df.x.mean()) ** 2) / tot) if tot > 0 else np.nan


def mundlak(df, target, feat):
    """target ~ within(feat) + between(feat) + (1 | source), REML (lmm_gls; verified
    against statsmodels MixedLM in tests/test_kag_models.py)."""
    W, B, _ = within_between(df[[feat]].values, df.source.values)
    X = np.column_stack([np.ones(len(df)), W[:, 0], B[:, 0]])
    beta, cov, tau, sig = lmm_gls(df[target].values, X, df.source.values)
    gap = beta[2] - beta[1]
    se_gap = np.sqrt(cov[2, 2] + cov[1, 1] - 2 * cov[1, 2])
    return dict(beta_within=beta[1], se_within=np.sqrt(cov[1, 1]),
                beta_between=beta[2], se_between=np.sqrt(cov[2, 2]),
                gap=gap, z_gap=gap / se_gap, tau=tau, sig=sig)


def main():
    rows, summ = [], {}
    for name in K.LOADERS:
        df = K.load(name)
        feats = K.FEATURES[name]
        df["r"] = df.y - df.m
        n_s = df.groupby("source").size()
        m0 = KnowledgeAnchoredLMM(np.zeros(0, int), n_starts=4).fit(df.r.values, np.zeros((len(df), 0)), df.source.values)
        ratio = np.exp(df.r)
        summ[name] = dict(
            n=len(df), sources=int(n_s.size), sources_ge6=int((n_s >= 6).sum()),
            specimens_in_ge6=int(n_s[n_s >= 6].sum()), singleton_sources=int((n_s == 1).sum()),
            anchor_ratio_mean=float(ratio.mean()), anchor_ratio_cov=float(ratio.std(ddof=1) / ratio.mean()),
            anchor_unconservative=float((ratio < 1).mean()),
            resid_tau=m0.tau_, resid_sig=m0.sig_, resid_icc=m0.tau_ ** 2 / (m0.tau_ ** 2 + m0.sig_ ** 2),
        )
        # joint within-between fit of the anchor residual: deviations from the anchor's exponents
        Phi = df[feats].values
        W, B, _ = within_between(Phi, df.source.values)
        p = len(feats)
        wb = KnowledgeAnchoredLMM([0] * p + [1] * p, n_starts=4).fit(df.r.values, np.column_stack([W, B]), df.source.values)
        rel = wb.reliance()
        sd = np.sqrt(np.diag(wb.b_cov_))
        summ[name].update(wb_lambda_within=float(wb.lam_[0]), wb_lambda_between=float(wb.lam_[1]),
                          wb_tau=wb.tau_, wb_sig=wb.sig_)
        for j, f in enumerate(feats):
            x = df[f].values
            sd_within = df.groupby("source")[f].transform(lambda v: v.std(ddof=0) if len(v) > 1 else 0.0)
            varying = df.assign(sdw=sd_within).groupby("source").sdw.first()
            rec = dict(dataset=name, feature=f, label=K.FEATURE_LABELS[f],
                       between_share=between_share(x, df.source.values),
                       programmes_varying=int((varying > 0.05).sum()),
                       programmes_total=int(n_s.size),
                       wb_dev_within=wb.b_[j], wb_dev_within_sd=sd[j], wb_reliance_within=rel[j],
                       wb_dev_between=wb.b_[p + j], wb_dev_between_sd=sd[p + j], wb_reliance_between=rel[p + j])
            for tgt, tag in (("r", "anchor_resid"), ("y", "lnV")):
                mk = mundlak(df, tgt, f)
                rec.update({f"{tag}_{k}": v for k, v in mk.items()})
            rows.append(rec)
    feat = pd.DataFrame(rows)
    feat.to_csv(OUT / "confounding_features.csv", index=False)
    (OUT / "confounding_summary.json").write_text(json.dumps(summ, indent=2))
    pd.set_option("display.width", 220)
    cols = ["dataset", "feature", "between_share", "programmes_varying", "programmes_total",
            "lnV_beta_within", "lnV_se_within", "lnV_beta_between", "lnV_se_between", "lnV_z_gap",
            "anchor_resid_beta_within", "anchor_resid_beta_between", "anchor_resid_z_gap",
            "wb_reliance_within"]
    print(feat[cols].round(3).to_string(index=False))
    print(json.dumps(summ, indent=2))


if __name__ == "__main__":
    main()
