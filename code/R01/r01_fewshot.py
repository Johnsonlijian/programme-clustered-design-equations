"""R01 diagnostic 2: leave-one-programme-out k-shot benchmark on FRP and SFRC.

Usage:
  python -X utf8 r01_fewshot.py --smoke      # one programme per dataset, 5 draws
  python -X utf8 r01_fewshot.py              # all programmes with >= MIN_N specimens

Outputs (round-local, regenerated by this script):
  outputs/fewshot_per_draw.csv.gz, outputs/fewshot_per_programme.csv,
  outputs/fewshot_summary.csv, outputs/fewshot_fit_info.json, outputs/input_manifest.csv
"""
from __future__ import annotations

import argparse
import json
import os
import time
from pathlib import Path

import pandas as pd
from joblib import Parallel, delayed

import kag_data as K
from kag_bench import ALL_METHODS, run_programme, summarise

OUT = Path(__file__).resolve().parents[1] / "outputs"
OUT.mkdir(exist_ok=True)
MIN_N = 6


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--draws", type=int, default=40)
    a = ap.parse_args()
    os.environ.setdefault("PYTHONPATH", str(Path(__file__).resolve().parent))
    frames, infos = [], {}
    t0 = time.time()
    for name in K.LOADERS:
        df = K.load(name)
        feats = K.FEATURES[name]
        n_s = df.groupby("source").size()
        targets = sorted(n_s[n_s >= MIN_N].index)
        if a.smoke:
            targets = targets[:1]
        draws = 5 if a.smoke else a.draws
        res = Parallel(n_jobs=1 if a.smoke else a.jobs, backend="loky")(
            delayed(run_programme)(df, feats, t, ALL_METHODS, draws, 0, 2) for t in targets)
        for t, (rows, info) in zip(targets, res):
            rows.insert(0, "dataset", name)
            frames.append(rows)
            infos[f"{name}::{t}"] = info
        print(f"{name}: {len(targets)} programmes done at {time.time() - t0:.0f}s", flush=True)
    per_draw = pd.concat(frames, ignore_index=True)
    tag = "_smoke" if a.smoke else ""
    per_draw.to_csv(OUT / f"fewshot_per_draw{tag}.csv.gz", index=False)
    per_prog, summ = summarise(per_draw)
    per_prog.to_csv(OUT / f"fewshot_per_programme{tag}.csv", index=False)
    summ.to_csv(OUT / f"fewshot_summary{tag}.csv", index=False)
    (OUT / f"fewshot_fit_info{tag}.json").write_text(json.dumps(infos, indent=1, default=float))
    K.manifest().to_csv(OUT / "input_manifest.csv", index=False)
    pd.set_option("display.width", 250)
    piv = summ.pivot_table(index=["dataset", "method"], columns="k", values="rmse").round(3)
    print(piv.to_string())
    cols = ["dataset", "k", "method", "programmes", "rmse", "rmse_lo", "rmse_hi", "rmse_minus_ref",
            "rmse_minus_ref_lo", "rmse_minus_ref_hi", "ref_better_share", "cover90", "unconservative"]
    print(summ[summ.k.isin([0, 3])][cols].round(3).to_string(index=False))
    print(f"total {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
